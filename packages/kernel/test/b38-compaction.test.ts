import { expect, test } from "bun:test"
import { createSessionActor } from "../src/session-actor"
import { createHarness, createManualEngine, flush } from "./helpers"

test("plugin autocontinue=false suppresses a saved follow-up after successful compaction", async () => {
  const h = createHarness()
  const manual = createManualEngine()
  const sessionId = h.ids("session")
  const clientId = h.ids("client")
  const actor = createSessionActor({ sessionId, clock: h.clock, scope: h.root.child("session"), engine: manual.engine, sink: h.sink, ids: h.ids })
  await actor.handle({ id: h.ids("command"), clientId, type: "session.compact", sessionId })
  await flush()
  expect(manual.last().phase).toBe("compaction")
  await actor.handle({ id: h.ids("command"), clientId, type: "session.compaction.set", sessionId, turnId: manual.last().input.turnId, text: "continue work" })
  manual.last().finish({ status: "ok", compacted: true, continueAfterCompact: false })
  await flush()
  expect(manual.turns).toHaveLength(1)
  expect(h.events.some((event) => event.type === "queue.added" && event.text === "continue work")).toBe(false)
  expect(actor.snapshot().foreground).toBe("idle")
  h.root.dispose()
})

test("an engine compacting inside a turn makes the session compacting until it ends, and reports it once", async () => {
  const h = createHarness()
  const manual = createManualEngine()
  const sessionId = h.ids("session")
  const actor = createSessionActor({ sessionId, clock: h.clock, scope: h.root.child("session"), engine: manual.engine, sink: h.sink, ids: h.ids })
  await actor.handle({ id: h.ids("command"), clientId: h.ids("client"), type: "user.submit", sessionId, text: "go", attachments: [] })
  await flush()
  const turn = manual.last()
  const itemId = h.ids("item")
  turn.input.emit({ type: "item.started", itemId, kind: "compaction", meta: { compactionMethod: "Claude Code" } })
  await flush()
  expect(actor.snapshot().foreground).toBe("compacting")
  turn.input.emit({ type: "item.completed", itemId, status: "ok", text: "Claude Code compacted its context." })
  await flush()
  expect(actor.snapshot().foreground).toBe("generating")
  turn.finish({ status: "ok" })
  await flush()
  const updates = h.events.filter((event) => event.type === "compaction.updated").map((event) => event.type === "compaction.updated" && [event.reason, event.state])
  expect(updates).toEqual([["auto", "writing"], ["auto", "packed"]])
  expect(actor.snapshot().foreground).toBe("idle")
  h.root.dispose()
})

test("a turn that ends while its engine compacts reports that compaction interrupted, once", async () => {
  const h = createHarness()
  const manual = createManualEngine()
  const sessionId = h.ids("session")
  const actor = createSessionActor({ sessionId, clock: h.clock, scope: h.root.child("session"), engine: manual.engine, sink: h.sink, ids: h.ids })
  await actor.handle({ id: h.ids("command"), clientId: h.ids("client"), type: "user.submit", sessionId, text: "go", attachments: [] })
  await flush()
  manual.last().input.emit({ type: "item.started", itemId: h.ids("item"), kind: "compaction" })
  await flush()
  manual.last().finish({ status: "error", code: "stream_idle", message: "gone" })
  await flush()
  const states = h.events.filter((event) => event.type === "compaction.updated").map((event) => event.type === "compaction.updated" && event.state)
  expect(states).toEqual(["writing", "interrupted"])
  h.root.dispose()
})
