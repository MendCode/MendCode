import { afterEach, describe, expect, test } from "bun:test"
import { readFileSync, symlinkSync } from "node:fs"
import path from "node:path"
import { parseAgentFile } from "@mendcode/packages"
import { AgentCreateReport, AgentDebugReport, type AgentsReport } from "@mendcode/protocol"
import { AGENT_CREATE_PERMISSIONS } from "@mendcode/protocol/wire"
import { parseAutomation, runAutomation } from "../../../apps/cli/src/automation"
import { boot, put, stop, type NativeHarness } from "./native-harness"

const harnesses: NativeHarness[] = []
afterEach(async () => { for (const h of harnesses.splice(0)) await h.cleanup() })
const start = async () => { const h = await boot(); harnesses.push(h); return h }
const error = (ack: { ok: boolean }) => (ack as { ok: false; error: { code: string; message: string } }).error

describe("B66 agent creation over the socket", () => {
  test("valid frontmatter roundtrips quotes and model; project trust still gates selection", async () => {
    const h = await start()
    const description = 'Review "quoted": diffs and \\paths'
    const created = await h.client.createAgent({ directory: h.project, scope: "project", name: "reviewer", description, mode: "all", permissions: ["read", "grep"], model: "gpt-6-luna" })
    expect(created.ok).toBe(true)
    if (!created.ok) throw new Error(created.error.message)
    expect(AgentCreateReport.safeParse(created.report).success).toBe(true)
    expect(created.report.file).toBe(path.join(h.project, ".mendcode", "agents", "reviewer.md"))
    const parsed = parseAgentFile({ text: readFileSync(created.report.file, "utf8"), stem: "reviewer", file: created.report.file, source: "project" })
    expect(parsed).toMatchObject({ agent: { description, prompt: description, model: "gpt-6-luna", mode: "all", permissionRules: expect.arrayContaining([{ permission: "edit", pattern: "*", action: "deny" }, { permission: "task", pattern: "*", action: "deny" }]) } })
    const listed = await h.client.send({ type: "agents.list", directory: h.project })
    if (!listed.ok) throw new Error(listed.error.message)
    expect((listed.result as AgentsReport).agents.find((agent) => agent.name === "reviewer")?.trusted).toBe(false)
    expect((await h.client.debugAgent({ directory: h.project, name: "reviewer" })).ok).toBe(false)
    await h.client.send({ type: "tools.trust", directory: h.project, trusted: true })
    const debug = await h.client.debugAgent({ directory: h.project, name: "reviewer" })
    expect(debug.ok).toBe(true)
    if (!debug.ok) throw new Error(debug.error.message)
    expect(AgentDebugReport.safeParse(debug.report).success).toBe(true)
    expect(debug.report.tools).toMatchObject({ read: true, write: false, probe: true, task: false })
    expect(h.requests).toEqual([])
  })
  test("user agents load immediately; arbitrary --path appends agents; duplicates and symlinks never overwrite", async () => {
    const h = await start()
    const input = { directory: h.project, scope: "user" as const, name: "reviewer", description: "Review", mode: "primary" as const, permissions: [...AGENT_CREATE_PERMISSIONS] }
    const [one, two] = await Promise.all([h.client.createAgent(input), h.client.createAgent(input)])
    expect([one.ok, two.ok].sort()).toEqual([false, true])
    const file = path.join(h.dir, "agents", "reviewer.md")
    const text = readFileSync(file, "utf8")
    expect(text).not.toContain("permission:")
    expect(error(await h.client.send({ ...input, type: "agent.create", description: "Overwrite" })).message).toContain("already exists")
    expect(readFileSync(file, "utf8")).toBe(text)
    const custom = await h.client.createAgent({ ...input, path: path.join(h.project, "config"), name: "custom" })
    expect(custom.ok && custom.report.file).toBe(path.join(h.project, "config", "agents", "custom.md"))
    const target = path.join(h.project, "target.md")
    put(target, "Keep me")
    symlinkSync(target, path.join(h.dir, "agents", "symlink.md"))
    expect((await h.client.createAgent({ ...input, name: "symlink" })).ok).toBe(false)
    expect(readFileSync(target, "utf8")).toBe("Keep me")
    expect((await h.client.createAgent({ ...input, name: "build" })).ok).toBe(false)
  })
  test("empty allow selection denies every available permission; fully explicit CLI uses the actual daemon", async () => {
    const h = await start()
    const created = await h.client.createAgent({ directory: h.project, scope: "user", name: "locked", description: "Locked", mode: "subagent", permissions: [] })
    expect(created.ok && created.report.agent.permissionRules).toHaveLength(AGENT_CREATE_PERMISSIONS.length)
    const parsed = parseAutomation(["agent", "create", "--path", h.dir, "--description", "CLI scout", "--mode", "subagent", "--permissions", "", "--model", "chatgpt/gpt-6-luna", "--json"])
    if (parsed.ok !== true) throw new Error(JSON.stringify(parsed))
    let stdout = "", stderr = ""
    const code = await runAutomation(parsed.command, { client: h.client, cwd: h.project, now: Date.now, listen: () => {}, onInterrupt: () => {}, out: { write: (text) => { stdout += text } }, err: { write: (text) => { stderr += text } } })
    expect({ code, stderr }).toEqual({ code: 0, stderr: "" })
    expect(JSON.parse(stdout)).toMatchObject({ command: "agent.create", data: { generation: "deterministic", agent: { model: "gpt-6-luna", mode: "subagent" } } })
    expect(readFileSync(path.join(h.dir, "agents", "cli-scout.md"), "utf8")).not.toContain("permission:")
  })
})

describe("R2 agent creation with model generation", () => {
  const json = (value: unknown) => JSON.stringify(value)
  const input = (h: NativeHarness) => ({ directory: h.project, scope: "user" as const, description: "Review diffs for risky changes", mode: "all" as const, permissions: ["read", "grep"] as ("read" | "grep")[], generate: true })
  test("the model writes identifier, when-to-use text and prompt; --model is used for the call and stored", async () => {
    const calls: { model?: string; prompt: string }[] = []
    const h = await boot({ complete: async (request) => { calls.push({ ...(request.model ? { model: request.model.model } : {}), prompt: request.prompt }); return "```json\n" + json({ identifier: "Diff Reviewer!", whenToUse: "Use this agent when a diff needs review. <example>Context: x</example>", systemPrompt: "You are a careful reviewer.\nYou will flag risks." }) + "\n```" } })
    harnesses.push(h)
    const created = await h.client.createAgent({ ...input(h), model: "gpt-6-sol" })
    if (!created.ok) throw new Error(created.error.message)
    expect(AgentCreateReport.safeParse(created.report).success).toBe(true)
    expect(created.report).toMatchObject({ generation: "model", callsProviders: true, file: path.join(h.dir, "agents", "diff-reviewer.md") })
    expect(created.report.fallback).toBeUndefined()
    expect(calls).toHaveLength(1)
    expect(calls[0]).toMatchObject({ model: "gpt-6-sol" })
    expect(calls[0]!.prompt).toContain("Review diffs for risky changes")
    const parsed = parseAgentFile({ text: readFileSync(created.report.file, "utf8"), stem: "diff-reviewer", file: created.report.file, source: "user" })
    expect(parsed).toMatchObject({ agent: { description: "Use this agent when a diff needs review.", prompt: "You are a careful reviewer.\nYou will flag risks.", model: "gpt-6-sol", mode: "all" } })
    expect(readFileSync(created.report.file, "utf8")).toContain("  edit: deny")
  })
  test("existing names are avoided, an explicit name wins, and secrets in the answer are redacted", async () => {
    let answer = json({ identifier: "reviewer", whenToUse: "Use this agent when reviewing.", systemPrompt: "You review. key sk-abcdefghijklmnopqrstuvwxyz0123456789" })
    const h = await boot({ complete: async () => answer })
    harnesses.push(h)
    put(path.join(h.dir, "agents", "reviewer.md"), "---\ndescription: Existing\n---\nExisting")
    const second = await h.client.createAgent(input(h))
    expect(second.ok && second.report.file).toBe(path.join(h.dir, "agents", "reviewer-2.md"))
    if (second.ok) expect(readFileSync(second.report.file, "utf8")).not.toContain("sk-abcdefghijklmnopqrstuvwxyz")
    const named = await h.client.createAgent({ ...input(h), name: "mine" })
    expect(named.ok && named.report.file).toBe(path.join(h.dir, "agents", "mine.md"))
    answer = json({ identifier: "build", whenToUse: "Use this agent when x.", systemPrompt: "You x." })
    const reserved = await h.client.createAgent(input(h))
    expect(reserved.ok && reserved.report.file).toBe(path.join(h.dir, "agents", "build-2.md"))
  })
  test("failure, unusable answers, unavailable model and a missing helper fall back to the deterministic file", async () => {
    let answer: string | Error = new Error("provider down")
    const h = await boot({ complete: async () => { if (answer instanceof Error) throw answer; return answer } })
    harnesses.push(h)
    const failed = await h.client.createAgent({ ...input(h), name: "one" })
    expect(failed.ok && failed.report).toMatchObject({ generation: "deterministic", callsProviders: true, fallback: "Generation failed: provider down" })
    expect(readFileSync(path.join(h.dir, "agents", "one.md"), "utf8")).toContain("Review diffs for risky changes")
    answer = "not json"
    const junk = await h.client.createAgent(input(h))
    expect(junk.ok && junk.report).toMatchObject({ generation: "deterministic", fallback: "Generation returned an unusable answer", file: path.join(h.dir, "agents", "review-diffs-for-risky-changes.md") })
    answer = json({ identifier: "x", whenToUse: "", systemPrompt: "p" })
    const empty = await h.client.createAgent({ ...input(h), name: "two" })
    expect(empty.ok && empty.report.fallback).toBe("Generation returned an unusable answer")
    const plain = await h.client.createAgent({ ...input(h), name: "three", generate: false })
    expect(plain.ok && plain.report).toMatchObject({ generation: "deterministic", callsProviders: false })
    const none = await boot()
    harnesses.push(none)
    const missing = await none.client.createAgent({ ...input(none), name: "four" })
    expect(missing.ok && missing.report).toMatchObject({ generation: "deterministic", callsProviders: false, fallback: "Generation needs the native engine" })
  })
})

describe("B66 native debug tool execution", () => {
  test("read and write execute with a durable debug transcript and no provider calls", async () => {
    const h = await start()
    put(path.join(h.project, "input.txt"), "Read this")
    const read = await h.client.debugAgent({ directory: h.project, name: "build", tool: "read", params: { path: "input.txt" } })
    expect(read.ok).toBe(true)
    if (!read.ok) throw new Error(read.error.message)
    expect(AgentDebugReport.safeParse(read.report).success).toBe(true)
    expect(read.report.result?.output).toContain("Read this")
    expect(read.report.sessionId).toBeDefined()
    expect(h.store.readAfter(read.report.sessionId!, 0, 100).some((event) => event.type === "item.completed")).toBe(true)
    const written = await h.client.debugAgent({ directory: h.project, name: "build", tool: "write", params: { path: "output.txt", content: "Written" } })
    expect(written.ok && written.report.result?.isError).toBe(false)
    expect(readFileSync(path.join(h.project, "output.txt"), "utf8")).toBe("Written")
    expect(h.requests).toEqual([])
  })
  test("denied tools, path rules, global rules and plan cap refuse execution; invalid args are errors", async () => {
    const h = await start()
    put(path.join(h.dir, "agents", "reviewer.md"), '---\ndescription: Review\npermission:\n  edit: deny\n  read:\n    "*private*": deny\n---\nReview')
    put(path.join(h.project, "private.txt"), "Private")
    const denied = await h.client.debugAgent({ directory: h.project, name: "reviewer", tool: "write", params: { path: "new.txt", text: "no" } })
    expect(denied.ok).toBe(false)
    const pathDenied = await h.client.debugAgent({ directory: h.project, name: "reviewer", tool: "read", params: { path: "private.txt" } })
    expect(pathDenied.ok && pathDenied.report.result).toMatchObject({ isError: true, output: expect.stringContaining("permission rule") })
    expect((await h.client.debugAgent({ directory: h.project, name: "plan", tool: "write", params: { path: "plan.txt", text: "no" } })).ok).toBe(false)
    await h.client.send({ type: "settings.set", patch: { tools: { write: false } } })
    expect((await h.client.debugAgent({ directory: h.project, name: "build", tool: "write", params: { path: "global.txt", text: "no" } })).ok).toBe(false)
    const invalid = await h.client.debugAgent({ directory: h.project, name: "build", tool: "read", params: { path: 5 } })
    expect(invalid.ok && invalid.report.result).toMatchObject({ isError: true, output: expect.stringContaining("invalid arguments") })
    expect((await h.client.debugAgent({ directory: h.project, name: "ghost" })).ok).toBe(false)
    expect((await h.client.debugAgent({ directory: h.project, name: "build", tool: "ghost" })).ok).toBe(false)
    expect(h.requests).toEqual([])
  })
  test("subagents keep their allow list and main-only restrictions", async () => {
    const h = await start()
    put(path.join(h.dir, "agents", "scout.md"), "---\ndescription: Scout\nmode: subagent\ntools: [read]\n---\nScout")
    const report = await h.client.debugAgent({ directory: h.project, name: "scout" })
    expect(report.ok && report.report.tools).toMatchObject({ read: true, write: false, probe: false })
    expect(report.ok && report.report.tools.plan_submit).toBeUndefined()
    const builtin = await h.client.debugAgent({ directory: h.project, name: "explore" })
    expect(builtin.ok && builtin.report.agent.mode).toBe("subagent")
    expect(h.requests).toEqual([])
  })
  test("hosted tasks use the daemon task port and report provider use; secret inventory remains model-free", async () => {
    const h = await boot({ steps: [stop("Inspected files")] })
    harnesses.push(h)
    const result = await h.client.debugAgent({ directory: h.project, name: "build", tool: "task", params: { description: "Inspect files", prompt: "Inspect project files", subagent_type: "explore" } })
    expect(result.ok && result.report.result).toMatchObject({ isError: false, output: expect.stringContaining("Inspected files") })
    expect(result.ok && result.report.callsProviders).toBe(true)
    expect(h.requests).toHaveLength(1)
    const inventory = await h.client.debugAgent({ directory: h.project, name: "build", tool: "secrets", params: {} })
    expect(inventory.ok && inventory.report.callsProviders).toBe(false)
    expect(h.requests).toHaveLength(1)
  })
})
