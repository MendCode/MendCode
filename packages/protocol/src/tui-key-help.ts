const words = (text: string) => text.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase().split(/[^a-z0-9]+/).filter((word) => word.length >= 2)
const STOP = new Set(["the", "on", "in", "of", "a", "an", "and", "or", "to", "by", "is", "it", "my", "me", "i", "do", "be", "at", "as", "for", "with", "show", "hide", "remove", "change", "make", "set", "turn", "off", "put", "want", "see", "dont", "stop", "please", "every", "each", "all", "any", "like", "when", "while", "this", "that"])
const stem = (word: string) => word.length > 4 && word.endsWith("ies") ? `${word.slice(0, -3)}y` : word.length > 3 && word.endsWith("s") && !word.endsWith("ss") ? word.slice(0, -1) : word
/** Words a user says for a part of the screen that the help text calls something else. */
const SYNONYMS: Readonly<Record<string, string>> = { statusbar: "footer", statusline: "footer", topbar: "top", toolbar: "bar", frame: "box", input: "prompt", composer: "prompt", textbox: "prompt", splash: "home", welcome: "home", start: "home", startup: "home", landing: "home", colour: "color", dark: "theme", light: "theme", thought: "reasoning", clock: "time", working: "activity", padding: "spacing" }


/** The keys a few words describe, best first: key name (and what users call it) and help text, each word stemmed; at most `limit`. */
export function findProfileKeys(query: string, limit = 8): string[] {
  const wanted = [...new Set(words(query).filter((word) => !STOP.has(word)).flatMap((word) => [stem(word), ...(SYNONYMS[word] ? [stem(SYNONYMS[word]!)] : [])]))]
  if (!wanted.length) return []
  const exact = query.replace(/[^a-z]/gi, "").toLowerCase()
  const scored = Object.keys(TUI_DEFAULTS).map((key) => {
    const name = new Set(words(`${key} ${PROFILE_KEY_ALIASES[key] ?? ""}`).map(stem))
    const help = new Set(words(PROFILE_KEY_HELP[key] ?? "").map(stem))
    const hits = wanted.filter((word) => name.has(word) || help.has(word)).length
    const score = wanted.reduce((sum, word) => sum + (name.has(word) ? 3 : 0) + (help.has(word) ? 2 : 0), 0) + (hits === wanted.length ? 2 : 0) + (key.toLowerCase() === exact ? 10 : 0)
    return { key, score: LEGACY_PROFILE_KEYS.has(key) ? score / 2 : score }
  })
  return scored.filter((row) => row.score > 0).sort((a, b) => b.score - a.score).slice(0, limit).map((row) => row.key)
}

/** One key as `customize_ui keys` returns it: what it changes, its type and allowed values, the default and the value now. */
export function describeProfileKey(key: string, profile: Record<string, unknown>) {
  const fallback = TUI_DEFAULTS[key]
  const type = Array.isArray(fallback) ? "array" : typeof fallback
  return { key, what: PROFILE_KEY_HELP[key] ?? "", type, ...(TUI_ENUMS[key] ? { values: TUI_ENUMS[key] } : {}), default: fallback, now: Object.hasOwn(profile, key) ? profile[key] : fallback }
}
