import { afterEach, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { readTuiProfile } from "../src/view/tui-profile"
import { appHarness, scratch } from "./extensions-harness"

const made: Array<ReturnType<typeof scratch>> = []
function layout() {
  const next = scratch()
  made.push(next)
  return next
}
afterEach(() => {
  for (const item of made.splice(0)) item.cleanup()
})

type Harness = Awaited<ReturnType<typeof appHarness>>
async function typeKeys(h: Harness, text: string) {
  for (const char of text) await h.key(char)
}
const command = async (h: Harness, text: string) => {
  await typeKeys(h, text)
  await h.key("\r")
}
/** A key no default binds. */
const F6 = "\x1b[17~"
const keybindings = (dataDir: string) => path.join(dataDir, "keybindings.json")
const bindingsFile = (dataDir: string) => JSON.parse(readFileSync(keybindings(dataDir), "utf8")) as Record<string, string | null>

describe("/vim", () => {
  test("toggles and persists, shows the mode above the prompt, and edits with normal-mode keys", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/vim")
    expect(readTuiProfile(dataDir).vimMode).toBe(true)
    expect(h.text()).toContain("-- INSERT --")
    await typeKeys(h, "hello world")
    await h.key("\x1b")
    expect(h.text()).toContain("-- NORMAL --")
    await typeKeys(h, "0dw")
    expect(h.app.editor.text).toBe("world")
    await typeKeys(h, "A!")
    expect(h.app.editor.text).toBe("world!")
    expect(h.text()).toContain("-- INSERT --")
    await h.key("\x1b")
    await typeKeys(h, "vbd")
    expect(h.app.editor.text).toBe("")
    await typeKeys(h, "u")
    expect(h.app.editor.text).toBe("world!")
    await h.key("\x12")
    expect(h.app.editor.text).toBe("")
  })

  test("Enter sends the prompt from normal mode and the next prompt starts in insert mode", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/vim on")
    await typeKeys(h, "ship it")
    await h.key("\x1b")
    await h.key("\r")
    expect(h.sent.some((sent) => sent.type === "user.submit" && sent.text === "ship it")).toBe(true)
    expect(h.app.editor.text).toBe("")
    expect(h.text()).toContain("-- INSERT --")
    await typeKeys(h, "next")
    expect(h.app.editor.text).toBe("next")
  })

  test("a stray letter in normal mode never lands in the prompt, and /vim off restores plain editing", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/vim")
    await typeKeys(h, "abc")
    await h.key("\x1b")
    await typeKeys(h, "zq")
    expect(h.app.editor.text).toBe("abc")
    await h.key("i")
    h.app.editor.clear()
    await command(h, "/vim off")
    expect(readTuiProfile(dataDir).vimMode).toBe(false)
    expect(h.text()).not.toContain("-- NORMAL --")
    await typeKeys(h, "plain")
    expect(h.app.editor.text).toBe("plain")
  })

  test("Esc drops a half-typed command instead of cancelling anything else", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/vim on")
    await typeKeys(h, "one two")
    await h.key("\x1b")
    await typeKeys(h, "2d")
    expect(h.text()).toContain("-- NORMAL --  2d")
    await h.key("\x1b")
    expect(h.text()).not.toContain("2d")
    await typeKeys(h, "x")
    expect(h.app.editor.text).toBe("one tw")
  })

  test("an unknown argument reports its usage and leaves the setting alone", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/vim maybe")
    expect(h.text()).toContain("usage: /vim [on|off|toggle]")
    expect(readTuiProfile(dataDir).vimMode).toBe(false)
  })
})

describe("/keymap", () => {
  test("lists actions with their keys and filters by what is typed", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    expect(h.text()).toContain("Keymap")
    expect(h.text()).toContain("prompt newline")
    expect(h.text()).toContain("shift+enter")
    await typeKeys(h, "widgets")
    expect(h.text()).toContain("1 actions")
    expect(h.text()).toContain("ctrl+t")
    await h.key("\x1b")
    expect(h.text()).toContain("type to filter")
    await h.key("\x1b")
    expect(h.text()).not.toContain("Keymap")
  })

  test("pressing a key rebinds the action: the file is written, the old key is freed and the new one works at once", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    await typeKeys(h, "session widgets")
    await h.key("\r")
    expect(h.text()).toContain("Press the key for session widgets")
    // ctrl+g is the comment key by default: it is offered as a conflict, not taken silently.
    await h.key("\x07")
    expect(h.text()).toContain("ctrl+g is bound to comment on")
    expect(existsSync(keybindings(dataDir))).toBe(false)
    await h.key("\x1b")
    await h.key("\r")
    await h.key(F6)
    expect(bindingsFile(dataDir)).toEqual({ "ctrl+t": null, f6: "dock" })
    expect(h.text()).toContain("session widgets: f6")
    await h.key("\x1b")
    await h.key("\x1b")
    expect(h.text()).not.toContain("Todos")
    await h.key("\x14")
    expect(h.text()).not.toContain("Todos")
    await h.key(F6)
    expect(h.text()).toContain("Todos")
  })

  test("a key that another action holds shows the conflict; esc keeps the file, enter replaces", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    await typeKeys(h, "session widgets")
    await h.key("\r")
    await h.key("\x0f")
    expect(h.text()).toContain("ctrl+o is bound to expand tool")
    expect(existsSync(keybindings(dataDir))).toBe(false)
    await h.key("\x1b")
    expect(existsSync(keybindings(dataDir))).toBe(false)
    expect(h.text()).toContain("cancelled")
    await h.key("\r")
    await h.key("\x0f")
    await h.key("\r")
    expect(bindingsFile(dataDir)["ctrl+o"]).toBe("dock")
    await h.key("\x1b")
    await typeKeys(h, "expand")
    expect(h.text()).toContain("unbound")
  })

  test("a leader chord, a reserved key and a key with no name are handled", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    await typeKeys(h, "session widgets")
    await h.key("\r")
    await h.key("\x18")
    expect(h.text()).toContain("chord key")
    await h.key("5")
    expect(bindingsFile(dataDir)["leader+5"]).toBe("dock")
    await h.key("\r")
    await h.key("\x03")
    expect(h.text()).toContain("ctrl+c is reserved")
    await h.key("\r")
    await h.key("q")
    expect(h.text()).toContain("that key has no name")
    expect(bindingsFile(dataDir)["leader+5"]).toBe("dock")
  })

  test("ctrl-d unbinds, ctrl-a adds a second key, ctrl-r resets the action", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    await typeKeys(h, "session widgets")
    await h.key("\x04")
    expect(bindingsFile(dataDir)).toEqual({ "ctrl+t": null })
    expect(h.text()).toContain("session widgets: unbound")
    await h.key("\x01")
    await h.key(F6)
    expect(bindingsFile(dataDir)).toEqual({ "ctrl+t": null, f6: "dock" })
    await h.key("\x12")
    expect(existsSync(keybindings(dataDir))).toBe(true)
    expect(bindingsFile(dataDir)).toEqual({})
    expect(h.text()).toContain("back to its")
  })

  test("entries the editor does not know are kept, a broken file is refused untouched, ctrl-g twice clears the file", async () => {
    const { dataDir, write } = layout()
    write("data/keybindings.json", JSON.stringify({ "alt+x": "command:fetch", leader: "ctrl+x" }))
    const h = await appHarness({ dataDir })
    await h.start()
    await command(h, "/keymap")
    await typeKeys(h, "session widgets")
    await h.key("\x04")
    expect(bindingsFile(dataDir)).toEqual({ "alt+x": "command:fetch", leader: "ctrl+x", "ctrl+t": null })
    await h.key("\x07")
    expect(h.text()).toContain("ctrl-g again resets")
    await h.key("\x07")
    expect(bindingsFile(dataDir)).toEqual({})
    writeFileSync(keybindings(dataDir), "{ not json")
    await h.key("\x04")
    expect(h.text()).toContain("not valid JSON")
    expect(readFileSync(keybindings(dataDir), "utf8")).toBe("{ not json")
  })
})

describe("/terminal-setup", () => {
  test("detects the terminal, prints its settings, and tells what a pressed key does; nothing is written", async () => {
    const { dataDir } = layout()
    const h = await appHarness({ dataDir, env: { TERM_PROGRAM: "WezTerm", WEZTERM_EXECUTABLE: "/usr/bin/wezterm" } })
    await h.start()
    await command(h, "/terminal-setup")
    expect(h.text()).toContain("Detected: WezTerm")
    expect(h.text()).toContain("wezterm.action.SendString")
    expect(h.text()).toContain("Press Shift+Enter now")
    await h.key("\r")
    expect(h.text()).toContain("enter: sends the prompt")
    await h.key("\x1b[13;2u")
    expect(h.text()).toContain("shift+enter: inserts a newline")
    await h.key("\x1b[B")
    expect(h.text()).toContain("Alacritty")
    expect(existsSync(keybindings(dataDir))).toBe(false)
    await h.key("\x1b")
    expect(h.text()).not.toContain("Terminal setup")
  })

  test("inside tmux the page adds the extended-keys settings", async () => {
    const h = await appHarness({ env: { TERM_PROGRAM: "iTerm.app", TMUX: "/tmp/tmux-1/default,1,0" } })
    await h.start()
    await command(h, "/terminal-setup")
    expect(h.text()).toContain("iTerm2 in tmux")
    expect(h.text()).toContain("extended-keys on")
  })

  test("renders without clipping at 60x20 and 180x50", async () => {
    for (const [width, height] of [[60, 20], [180, 50]] as const) {
      const h = await appHarness({ width, height, env: { TERM_PROGRAM: "ghostty" } })
      await h.start()
      await command(h, "/terminal-setup")
      expect(h.rows().length).toBeLessThanOrEqual(height)
      expect(Math.max(...h.rows().map((row) => [...row].length))).toBeLessThanOrEqual(width)
      expect(h.text()).toContain("Terminal setup")
      await h.key("\x1b")
      await command(h, "/keymap")
      expect(h.rows().length).toBeLessThanOrEqual(height)
      expect(Math.max(...h.rows().map((row) => [...row].length))).toBeLessThanOrEqual(width)
      expect(h.text()).toContain("Keymap")
    }
  })
})

/** Frames for the lead to read: written only when MENDCODE_FRAMES_DIR names a folder. */
describe.skipIf(!process.env.MENDCODE_FRAMES_DIR)("frames", () => {
  test("vim, keymap and terminal setup at 100x30 and 180x50", async () => {
    const dir = process.env.MENDCODE_FRAMES_DIR!
    mkdirSync(dir, { recursive: true })
    for (const [width, height] of [[100, 30], [180, 50]] as const) {
      const save = (h: Harness, name: string) => writeFileSync(path.join(dir, `${name}-${width}x${height}.txt`), `${h.text()}\n`)
      const { dataDir } = layout()
      const h = await appHarness({ dataDir, width, height, env: { TERM_PROGRAM: "WezTerm", WEZTERM_EXECUTABLE: "/usr/bin/wezterm" } })
      await h.start()
      await command(h, "/vim on")
      await typeKeys(h, "refactor the parser")
      await h.key("\x1b")
      await typeKeys(h, "2d")
      save(h, "vim-normal-pending")
      await h.key("\x1b")
      await typeKeys(h, "vb")
      save(h, "vim-visual")
      await h.key("\x1b")
      await h.key("\x03")
      await h.key("i")
      await command(h, "/keymap")
      save(h, "keymap-list")
      await typeKeys(h, "session widgets")
      await h.key("\r")
      await h.key("\x0f")
      save(h, "keymap-conflict")
      await h.key("\x1b")
      await h.key("\x1b")
      await h.key("\x1b")
      await command(h, "/terminal-setup")
      await h.key("\x1b[13;2u")
      save(h, "terminal-setup")
    }
  })
})
