import { afterEach, expect, test } from "bun:test"
import { b59Harness, B59_MEMORY } from "./b59-harness"
import { appHarness, cleanTemps, tempDir } from "./session-ui-harness"
import { textWidth } from "../src/view/wrap"
import { CUSTOMIZE_ROWS } from "../src/view/customize-page"
import { readTuiProfile } from "../src/view/tui-profile"

afterEach(cleanTemps)
const text = (h: ReturnType<typeof b59Harness>) => h.text().join("\n")

for (const [width, height] of [[60, 20], [100, 30], [160, 45], [180, 50], [220, 60]]) test(`compaction panels fill ${width}x${height}, keep hints in the header and an editor cursor inside the panel`, async () => {
  const h = b59Harness(width, height)
  h.begin()
  await h.type("/compaction\r")
  expect(h.app.page).toBe("compaction")
  expect(text(h)).toContain("Packing context")
  expect(text(h)).toContain("Capture transcript")
  expect(h.text()[0]).toContain("esc back")
  await h.app.onKey("e")
  await h.type("\x1b[200~" + Array.from({ length: 24 }, (_, i) => `Line ${i}: keep tests.`).join("\n") + "\x1b[201~")
  h.app.render()
  const frame = h.frames.at(-1)!
  expect(frame).toHaveLength(height!)
  expect(frame.every((row) => textWidth(row.map((span) => span.text).join("")) <= width!)).toBe(true)
  expect(text(h)).toContain("Line 23: keep tests.")
  expect(text(h)).toContain("┃")
  const cursor = h.cursors.at(-1)!
  expect(cursor.row).toBeGreaterThan(2)
  expect(cursor.row).toBeLessThan(height! - 2)
  expect(cursor.col).toBeGreaterThan(2)
  expect(h.text()[cursor.row]![cursor.col - 1]).toBe(".")
  expect(h.app.editor.text).toBe("")
  await h.app.onKey("\x03")
  expect(h.app.page).toBe("compaction")
  await h.app.onKey("\x1b")
})

test("scratchpad edits autosave, reopen, navigate and undo without submitting the prompt", async () => {
  const h = b59Harness()
  h.begin()
  await h.type("/compaction\r")
  await h.app.onKey("e")
  await h.type("test\rnext")
  await h.app.onKey("\x01")
  await h.app.onKey("\x1b[C")
  await h.type("X")
  expect(h.sentOf("session.compaction.set").at(-1)).toMatchObject({ text: "test\nnXext" })
  await h.app.onKey("\x1f")
  expect(h.sentOf("session.compaction.set").at(-1)).toMatchObject({ text: "test\nnext" })
  await h.app.onKey("\x19")
  expect(h.sentOf("session.compaction.set").at(-1)).toMatchObject({ text: "test\nnXext" })
  await h.app.onKey("\x1f")
  await h.app.onKey("\x1b")
  await h.app.onKey("\x1b")
  await h.type("/compaction\r")
  expect(text(h)).toContain("test")
  expect(text(h)).toContain("next")
  expect(h.sentOf("user.submit")).toHaveLength(0)
  expect(h.app.editor.text).toBe("")
  h.finish()
  await h.app.onKey("e")
  expect(h.cursors.at(-1)).toBeUndefined()
  expect(text(h)).toContain("Follow-up queued")
})

test("completion while editing stops further writes, and replay keeps the memory and follow-up", async () => {
  const h = b59Harness()
  h.begin()
  await h.type("/compaction\r")
  await h.app.onKey("e")
  await h.type("Keep tests")
  h.finish()
  const count = h.sentOf("session.compaction.set").length
  await h.type("discard")
  expect(h.sentOf("session.compaction.set")).toHaveLength(count)
  const replay = appHarness({ sessionId: h.sessionId, dataDir: tempDir() })
  for (const event of h.events.slice(1)) replay.app.onEvent(event)
  expect(replay.app.transcript.compactions()[0]?.followUp).toBe("Keep tests")
  replay.app.transcript.prepend(h.events.slice(0, 1))
  expect(replay.app.transcript.compactions()[0]?.followUp).toBe("Keep tests")
  await replay.type("/compaction\r")
  expect(replay.text().join("\n")).toContain("Keep tests")
  expect(replay.text().join("\n")).not.toContain("Implemented")
  await replay.app.onKey("m")
  replay.app.render()
  expect(replay.text().join("\n")).toContain("Implemented")
  expect(replay.app.transcript.compactions()[0]?.summary).toBe(B59_MEMORY)
  for (let i = 0; i < 100; i++) await replay.app.onKey("\x1b[B")
  expect(replay.text().join("\n")).toContain("Memory 30")
  expect(replay.text().join("\n")).not.toContain("Memory 1:")
})

test("quiet and minimal styles follow presentation, and the scratchpad preference hides its panel", async () => {
  const h = b59Harness()
  h.begin()
  h.profile({ presentation: "raw" })
  h.app.render()
  expect(text(h)).toContain("Packing context")
  expect(text(h)).not.toContain("Capture transcript")
  h.profile({ presentation: "minimal" })
  h.app.render()
  expect(text(h)).toContain("Packing context")
  expect(text(h)).not.toContain("Scratchpad")
  h.profile({ compactionStyle: "cockpit", compactionScratchpad: false })
  await h.type("/compaction\r")
  expect(text(h)).not.toContain("Scratchpad")
  await h.app.onKey("e")
  expect(h.cursors.at(-1)).toBeUndefined()
})

test("compaction customization persists, and cancelled panels retain their saved follow-up", async () => {
  const h = b59Harness(180, 50)
  h.begin()
  await h.type("/customize\r")
  for (let i = 0; i < CUSTOMIZE_ROWS.indexOf("compactionStyle"); i++) await h.app.onKey("\x1b[B")
  await h.app.onKey("\x1b[C")
  expect(readTuiProfile(h.dataDir).compactionStyle).toBe("minimal")
  expect(text(h)).toContain("Compaction panel")
  await h.app.onKey("\x1b")
  await h.type("/compaction\r")
  await h.app.onKey("e")
  await h.type("Retain this")
  await h.app.onKey("\x1b")
  h.finish("cancelled")
  expect(text(h)).toContain("Compaction cancelled")
  expect(text(h)).toContain("Retain this")
  expect(text(h)).not.toContain("Follow-up queued")
})

test("restart recovery interrupts a writing panel and preserves its note through history pagination", async () => {
  const h = b59Harness()
  h.begin()
  await h.type("/compaction\r")
  await h.app.onKey("e")
  await h.type("Keep this after restart")
  const turnId = h.app.transcript.compactions()[0]!.turnId
  h.chat.emit({ type: "turn.interrupted", turnId, reason: "restart" })
  h.chat.emit({ type: "foreground.state", state: "idle" })
  await h.app.onKey("\x1b")
  await h.app.onKey("\x1b")
  expect(text(h)).toContain("Compaction interrupted")
  h.app.transcript.prepend([{ ...h.events[0]!, seq: 0 }])
  await h.type("/compaction\r")
  expect(text(h)).toContain("Compaction interrupted")
  expect(text(h)).toContain("Keep this after restart")
})

test("large pasted drafts stay within the wire limit and clearing them autosaves an empty note", async () => {
  const h = b59Harness()
  h.begin()
  await h.type("/compaction\r")
  await h.app.onKey("e")
  await h.type("\x1b[200~" + "a".repeat(8100) + "\x1b[201~")
  expect(h.sentOf("session.compaction.set").at(-1)).toMatchObject({ text: "a".repeat(8000) })
  await h.app.onKey("\x1b[H")
  await h.app.onKey("\x1b[1;2F")
  await h.app.onKey("\x7f")
  expect(h.sentOf("session.compaction.set").at(-1)).toMatchObject({ text: "" })
  expect(h.app.editor.text).toBe("")
})
