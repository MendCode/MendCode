import { afterEach, expect, test } from "bun:test"
import { catalogHarness } from "./package-catalog-harness"
import { cleanTemps } from "./session-ui-harness"
import { textWidth } from "../src/view/wrap"

afterEach(cleanTemps)
test("marketplace search and preview preserve the prompt boundary; install is never an implicit Enter action", async () => {
  const h = catalogHarness()
  await h.type("/marketplace\r")
  expect(h.sentOf("packages.search")).toHaveLength(1)
  expect(h.text().join("\n")).toContain("Review Kit")
  await h.app.onKey("/")
  await h.type("terminal\r")
  expect(h.text().join("\n")).not.toContain("Review Kit")
  await h.app.onKey("\r")
  expect(h.sentOf("packages.preview").at(-1)).toMatchObject({ name: "terminal-kit", scope: "user" })
  expect(h.sentOf("packages.install-catalog")).toHaveLength(0)
  expect(h.text().join("\n")).toContain("0 audit problems")
  await h.app.onKey("p")
  await h.app.onKey("i")
  expect(h.text().join("\n")).toContain("Install terminal-kit in project?")
  await h.app.onKey("\x1b")
  expect(h.sentOf("packages.install-catalog")).toHaveLength(0)
  await h.app.onKey("i")
  await h.app.onKey("y")
  expect(h.sentOf("packages.install-catalog")).toMatchObject([{ name: "terminal-kit", sourceId: "team", scope: "project" }])
  expect(h.sentOf("user.submit")).toHaveLength(0)
  expect(h.text().join("\n")).toContain("active")
})

test("sources can be added off by default, explicitly enabled and removed with confirmation", async () => {
  const h = catalogHarness()
  await h.type("/marketplace\r")
  await h.app.onKey("s")
  await h.app.onKey("a")
  await h.type("extra\r")
  await h.type("/catalog/extra\r")
  expect(h.sentOf("packages.add-source").at(-1)).toMatchObject({ sourceId: "extra", location: "/catalog/extra", enabled: false })
  await h.app.onKey("j")
  await h.app.onKey("j")
  await h.app.onKey("e")
  expect(h.sentOf("packages.add-source").at(-1)).toMatchObject({ sourceId: "extra", enabled: true })
  await h.app.onKey("d")
  expect(h.sentOf("packages.remove-source")).toHaveLength(0)
  await h.app.onKey("y")
  expect(h.sentOf("packages.remove-source").at(-1)).toMatchObject({ sourceId: "extra" })
})

test("a remote catalog is added off, shown as remote and fetched only by the explicit u key", async () => {
  const h = catalogHarness()
  await h.type("/marketplace\r")
  await h.app.onKey("s")
  await h.app.onKey("a")
  await h.type("hub\r")
  await h.type("https://hub.example/index.json\r")
  expect(h.sentOf("packages.add-source").at(-1)).toMatchObject({ sourceId: "hub", location: "https://hub.example/index.json", enabled: false })
  expect(h.text().join("\n")).toContain("hub · off · remote")
  await h.app.onKey("j")
  await h.app.onKey("j")
  await h.app.onKey("\r")
  expect(h.text().join("\n")).toContain("Remote catalog")
  expect(h.text().join("\n")).toContain("Not fetched yet")
  expect(h.sentOf("packages.refresh")).toHaveLength(0)
  await h.app.onKey("u")
  expect(h.sentOf("packages.refresh")).toMatchObject([{ sourceId: "hub" }])
  expect(h.text().join("\n")).toContain("Fetched 2026-10-03 12:30")
  await h.app.onKey("k")
  await h.app.onKey("u")
  expect(h.sentOf("packages.refresh")).toHaveLength(1)
})

test("packages c opens the selected package's resources and space switches one through the daemon", async () => {
  const h = catalogHarness()
  await h.type("/packages\r")
  await h.app.onKey("c")
  await Bun.sleep(5)
  expect(h.sentOf("packages.config")).toMatchObject([{ key: "user:local-kit" }])
  expect(h.text().join("\n")).toContain("skills/deploy")
  await h.app.onKey("j")
  await h.app.onKey(" ")
  await Bun.sleep(5)
  expect(h.sentOf("packages.resource")).toMatchObject([{ key: "user:local-kit", resource: "commands/review", enabled: false }])
  expect(h.text().join("\n")).toMatch(/commands\/review\s+off/)
  await h.app.onKey("\x1b")
  expect(h.text()[0]).toContain("Packages")
  expect(h.text().join("\n")).not.toContain("Resources ·")
})

test("assets show real counts; packages offer marketplace and reversible deselect-all", async () => {
  const h = catalogHarness()
  await h.type("/mend-assets\r")
  expect(h.sentOf("packages.assets")).toHaveLength(1)
  expect(h.text().join("\n")).toContain("Skills: 2")
  expect(h.text().join("\n")).toContain("MCP files: 1")
  expect(h.text().join("\n")).toContain("Prompt templates: 2")
  expect(h.text().join("\n")).toContain("Prompt mode: focus")
  await h.app.onKey("\x1b")
  await h.type("/packages\r")
  await h.app.onKey("x")
  expect(h.sentOf("packages.disable-all")).toHaveLength(0)
  await h.app.onKey("y")
  await Bun.sleep(5)
  expect(h.sentOf("packages.disable-all")).toHaveLength(1)
  expect(h.sentOf("packages.remove")).toHaveLength(0)
  await h.app.onKey("m")
  expect(h.text()[0]).toContain("MendCode Marketplace")
})

test("page frames have visible panel borders, header hints and no overflow at every contracted size", async () => {
  for (const [width, height] of [[60, 20], [100, 30], [160, 45], [180, 50], [220, 60]] as const) {
    const h = catalogHarness(width, height)
    for (const command of ["/marketplace", "/mend-assets", "/packages"]) {
      await h.type(`${command}\r`)
      expect(h.text()).toHaveLength(height)
      for (const line of h.text()) expect(textWidth(line)).toBeLessThanOrEqual(width)
      expect(h.text()[0]).toContain("esc back")
      expect(h.text().join("\n")).toContain("┌─")
      expect(h.text().join("\n")).not.toContain("ready / today")
      if (width < 70) expect(h.text().some((row) => (row.match(/┌/g) ?? []).length > 1)).toBe(false)
      await h.app.onKey("\x1b")
    }
  }
}, 20_000)

