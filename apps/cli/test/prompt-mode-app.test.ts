import { afterEach, expect, test } from "bun:test"
import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { b05Harness } from "./b05-harness"
import { cleanTemps } from "./session-ui-harness"
import { CUSTOMIZE_ROWS } from "../src/view/customize-page"
import { SETUP_ROWS } from "../src/view/setup-page"
import { textWidth } from "../src/view/wrap"
afterEach(cleanTemps)

test("prompt aliases open the lazy picker; Tab completes without executing or changing mode", async () => {
  const h = b05Harness()
  await h.type("/prompt-mo")
  await h.app.onKey("\t")
  expect(h.app.page).toBe("chat")
  expect(h.sentOf("prompt.set")).toHaveLength(0)
  expect(h.sentOf("prompt.status")).toHaveLength(0)
  await h.app.onKey("\r")
  expect(h.app.page).toBe("prompt-mode")
  expect(h.text().join("\n")).toContain("Focus · active")
  expect(h.text().join("\n")).not.toContain("Project prompt · active")
  await h.app.onKey("\x1b")
  await h.type("/prompt-mode\r")
  expect(h.app.page).toBe("prompt-mode")
  await h.app.onKey("\x1b")
  // The old aliases are not commands any more: the line says where they went and the picker stays closed.
  for (const [alias, now] of [["prompt-context", "prompt-mode"]] as const) {
    await h.type(`/${alias}\r`)
    expect(h.app.page).toBe("chat")
    expect(h.text().join("\n")).toContain(`/${alias} is now /${now}`)
  }
})
test("selection, explicit mode, cycling and families persist via daemon commands; refusal preserves the picker", async () => {
  const h = b05Harness()
  await h.type("/prompt-mode minimal\r")
  expect(h.modes.status(h.directory).mode).toBe("minimal")
  await h.type("/prompt-mode cycle\r")
  expect(h.modes.status(h.directory).mode).toBe("focus")
  await h.type("/prompt-mode\r")
  await h.app.onKey("\x1b[B")
  await h.app.onKey("\r")
  expect(h.app.page).toBe("chat")
  expect(h.modes.status(h.directory).mode).toBe("guide")
  await h.type("/prompt-mode\r")
  await h.app.onKey("\t")
  expect(h.text().join("\n")).toContain("auto → neutral")
  await h.app.onKey("\x1b[B")
  await h.app.onKey("\x1b[B")
  await h.app.onKey("\r")
  expect(h.modes.status(h.directory).focusID).toBe("claude")
  await h.type("/prompt-mode\r")
  h.refuse("Mode was not saved")
  await h.app.onKey("\r")
  expect(h.app.page).toBe("prompt-mode")
  expect(h.text().join("\n")).toContain("Mode was not saved")
  expect(h.modes.status(h.directory).mode).toBe("guide")
})
test("choosing a mode says what it adds to every call; guide and full warn, focus and minimal do not; the picker shows it too", async () => {
  const h = b05Harness()
  await h.type("/prompt-mode guide\r")
  const guide = h.text().join("\n")
  expect(guide).toMatch(/guide · \+[\d,]+ tokens per call \([\d,]+ total\)/)
  expect(guide).toContain("sent with every call")
  await h.type("/prompt-mode focus\r")
  const focus = h.text().join("\n")
  expect(focus).toMatch(/focus · [\d,]+ tokens per call/)
  expect(focus).not.toContain("sent with every call")
  await h.type("/prompt-mode\r")
  expect(h.app.page).toBe("prompt-mode")
  const picker = h.text().join("\n")
  expect(picker).toMatch(/guide|full/)
  expect(picker).toMatch(/tokens per call/)
})
test("the setup and customize rows of the prompt context show the per-call cost of the current mode", async () => {
  const h = b05Harness()
  await h.type("/prompt-mode guide\r")
  await h.type("/setup advanced\r")
  for (let i = 0; i < SETUP_ROWS.indexOf("promptContext"); i++) await h.app.onKey("\x1b[B")
  expect(h.text().join("\n")).toMatch(/guide · \+[\d,]+ tokens per call/)
  await h.app.onKey("\x1b")
  await h.type("/customize\r")
  for (let i = 0; i < CUSTOMIZE_ROWS.indexOf("promptContext"); i++) await h.app.onKey("\x1b[B")
  expect(h.text().join("\n")).toMatch(/guide · \+[\d,]+ tokens per call/)
})
test("custom is selectable only with a valid project source and shows its real name and byte count", async () => {
  const h = b05Harness()
  mkdirSync(path.join(h.directory, ".mendcode", "prompts"), { recursive: true })
  writeFileSync(path.join(h.directory, ".mendcode", "prompts", "custom.md"), "---\nname: API work\n---\nUse focused patches")
  await h.type("/prompt-mode\r")
  await h.app.onKey("\x1b[B")
  await h.app.onKey("\x1b[B")
  await h.app.onKey("\x1b[B")
  expect(h.text().join("\n")).toContain("API work")
  expect(h.text().join("\n")).toContain("19 bytes")
  await h.app.onKey("\r")
  expect(h.modes.status(h.directory).mode).toBe("custom")
})
test("setup and customization open the same prompt selector and return to their original page", async () => {
  const h = b05Harness()
  await h.type("/setup advanced\r")
  for (let i = 0; i < SETUP_ROWS.indexOf("promptContext"); i++) await h.app.onKey("\x1b[B")
  await h.app.onKey("\r")
  expect(h.app.page).toBe("prompt-mode")
  await h.app.onKey("\x1b")
  expect(h.app.page).toBe("setup")
  await h.app.onKey("\x1b")
  await h.type("/customize\r")
  for (let i = 0; i < CUSTOMIZE_ROWS.indexOf("promptContext"); i++) await h.app.onKey("\x1b[B")
  await h.app.onKey("\r")
  expect(h.app.page).toBe("prompt-mode")
  await h.app.onKey("\x1b")
  expect(h.app.page).toBe("customize")
})
test("new prompt screens fit compact through large terminal grids and focus stays visible", async () => {
  for (const [width, height] of [[60, 20], [100, 30], [160, 45], [180, 50], [220, 60]]) {
    const h = b05Harness(width, height)
    await h.type("/prompt-mode\r")
    await h.app.onKey("2")
    for (let i = 0; i < 6; i++) await h.app.onKey("\x1b[B")
    expect(h.text().join("\n")).toContain("› mistral")
    expect(h.frames.at(-1)).toHaveLength(height!)
    expect(h.text().every((row) => textWidth(row) <= width! && !row.includes("\x1b"))).toBe(true)
  }
})
